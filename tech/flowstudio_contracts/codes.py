"""错误码与缺陷码常量：前端、PM Agent、编排器、仓储共用同一份枚举。

IssueCode 只覆盖"缺陷定位"，RunFailureCode 覆盖"规划运行失败"，ErrorCode 覆盖
"HTTP 错误体"。三者语义不重叠，避免前端按字符串猜测含义。
"""

from __future__ import annotations

from enum import StrEnum
from typing import Final


class IssueCode(StrEnum):
    """ValidationReport.errors/warnings 的 code。"""

    SPEC_REQUIRED = "SPEC_REQUIRED"
    DUPLICATE_ID = "DUPLICATE_ID"
    MISSING_DEPENDENCY = "MISSING_DEPENDENCY"
    SELF_DEPENDENCY = "SELF_DEPENDENCY"
    DUPLICATE_DEPENDENCY = "DUPLICATE_DEPENDENCY"
    CYCLE = "CYCLE"
    INVALID_STAGE = "INVALID_STAGE"
    INVALID_ROLE = "INVALID_ROLE"
    INVALID_CATEGORY = "INVALID_CATEGORY"
    STAGE_EDGE_FORBIDDEN = "STAGE_EDGE_FORBIDDEN"
    MISSING_INPUT = "MISSING_INPUT"
    INPUT_NOT_DEPENDENCY = "INPUT_NOT_DEPENDENCY"
    UNKNOWN_REQUIREMENT = "UNKNOWN_REQUIREMENT"
    REQUIRED_UNCOVERED = "REQUIRED_UNCOVERED"
    REQUIRED_CATEGORY = "REQUIRED_CATEGORY"
    UNCONFIRMED_ASSUMPTION = "UNCONFIRMED_ASSUMPTION"
    CRITICAL_ASSUMPTION = "CRITICAL_ASSUMPTION"
    POSSIBLE_DUPLICATE = "POSSIBLE_DUPLICATE"
    ORPHAN = "ORPHAN"
    POLICY_UNSATISFIABLE = "POLICY_UNSATISFIABLE"
    SOURCE_MISMATCH = "SOURCE_MISMATCH"


class RunFailureCode(StrEnum):
    """PlanningRun.error.code 的取值；不含图校验缺陷（那属于 ValidationReport）。"""

    MODEL_SCHEMA = "MODEL_SCHEMA"
    MODEL_EMPTY = "MODEL_EMPTY"
    MODEL_TRUNCATED = "MODEL_TRUNCATED"
    MODEL_BUDGET = "MODEL_BUDGET"
    MODEL_TIMEOUT = "MODEL_TIMEOUT"
    MODEL_AUTH = "MODEL_AUTH"
    MODEL_RATE_LIMITED = "MODEL_RATE_LIMITED"
    MODEL_NETWORK = "MODEL_NETWORK"
    PROCESS_INTERRUPTED = "PROCESS_INTERRUPTED"
    POLICY_UNSATISFIABLE = "POLICY_UNSATISFIABLE"
    INTERNAL_ERROR = "INTERNAL_ERROR"


class ErrorCode(StrEnum):
    """错误响应体 {error:{code,...}} 的 code。"""

    VALIDATION_FAILED = "VALIDATION_FAILED"
    NOT_FOUND = "NOT_FOUND"
    REVISION_CONFLICT = "REVISION_CONFLICT"
    IDEMPOTENCY_CONFLICT = "IDEMPOTENCY_CONFLICT"
    PAYLOAD_TOO_LARGE = "PAYLOAD_TOO_LARGE"
    QUEUE_FULL = "QUEUE_FULL"
    STORAGE_BUSY = "STORAGE_BUSY"
    RESULT_NOT_READY = "RESULT_NOT_READY"
    ORIGIN_FORBIDDEN = "ORIGIN_FORBIDDEN"


ERROR_HTTP_STATUS: Final[dict[ErrorCode, int]] = {
    ErrorCode.VALIDATION_FAILED: 422,
    ErrorCode.NOT_FOUND: 404,
    ErrorCode.REVISION_CONFLICT: 409,
    ErrorCode.IDEMPOTENCY_CONFLICT: 409,
    ErrorCode.PAYLOAD_TOO_LARGE: 413,
    ErrorCode.QUEUE_FULL: 429,
    ErrorCode.STORAGE_BUSY: 503,
    ErrorCode.RESULT_NOT_READY: 409,
    ErrorCode.ORIGIN_FORBIDDEN: 403,
}

RETRYABLE_RUN_FAILURES: Final[frozenset[RunFailureCode]] = frozenset(
    {
        RunFailureCode.MODEL_TIMEOUT,
        RunFailureCode.MODEL_NETWORK,
        RunFailureCode.MODEL_RATE_LIMITED,
        RunFailureCode.PROCESS_INTERRUPTED,
    }
)
